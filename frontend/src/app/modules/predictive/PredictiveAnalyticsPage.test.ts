import { describe, expect, it } from "vitest";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import type { PredictiveForecast } from "../../types/predictive";
import { FORECAST_EVALUATION_DISCLOSURE, ingredientEvaluationStatus, ingredientEvaluationSummary, PredictiveAnalyticsSkeleton, predictiveCoverageLabel, predictiveDataSufficiency, predictiveInsightSourceLabel, predictiveScopeLabel, PROJECTED_COGS_DISCLOSURE, shouldApplyPredictiveResponse } from "./PredictiveAnalyticsPage";

type IngredientAccuracy = PredictiveForecast["accuracy"]["ingredients"][number];

const ingredientAccuracy = (overrides: Partial<IngredientAccuracy> = {}): IngredientAccuracy => ({
  branchId: "gulod", branchName: "Gulod / Main Branch", inventoryItemId: "ingredient", name: "Ingredient", unit: "g",
  evaluationStart: null, evaluationEnd: null, evaluatedDays: 0, observations: [], mae: null,
  averageActual: null, averageForecast: null, insufficientHistory: true, incompatibleUnits: false,
  ...overrides,
});

const forecastContext = (
  observedSalesDays: number,
  confidence: PredictiveForecast["methodology"]["confidence"],
  mae: number | null,
  evaluatedDays: number,
  branchName = "Gulod / Main Branch",
) => ({
  scope: { branchId: "branch-1" as string | null, branchName, forecastStart: "2026-10-02", forecastEnd: "2026-10-31", branchCoverage: undefined as PredictiveForecast["scope"]["branchCoverage"] },
  readiness: {
    status: observedSalesDays >= 28 ? "READY" as const : "PRELIMINARY" as const,
    minimumSalesDays: 28,
    observedSalesDays,
    comparisonPeriodAvailable: observedSalesDays >= 56,
    recommendationsActionable: observedSalesDays >= 28,
    reason: observedSalesDays >= 28 ? null : "At least 28 recorded sales days are required.",
  },
  methodology: {
    historicalStart: "2025-10-02", historicalEnd: "2026-10-01", observedSalesDays, confidence,
    insightSource: "SYSTEM_ANALYSIS" as const, disclaimer: "", salesMaeMethod: "", cogsMaeMethod: "", ingredientMaeMethod: "", shrinkageRateMethod: "", stockProjectionAssumption: "",
  },
  summary: {
    forecastSales: 0, demandChange: observedSalesDays >= 56 ? 0 : null, criticalItems: 0, projectedCogs: 0,
    projectedShrinkageRate: 0, projectedShrinkageCost: 0,
    shrinkageForecastStatus: "AVAILABLE" as PredictiveForecast["summary"]["shrinkageForecastStatus"], recommendedReorders: 0,
  },
  accuracy: {
    sales: {
      overall: {
        evaluationStart: evaluatedDays ? "2026-09-01" : null,
        evaluationEnd: evaluatedDays ? "2026-09-30" : null,
        evaluatedDays, observations: [], mae, averageActual: null, averageForecast: null,
        insufficientHistory: evaluatedDays < 30,
      },
      branches: [],
    },
    cogs: {
      overall: {
        evaluationStart: null, evaluationEnd: null, evaluatedDays: 0, observations: [], mae: null,
        averageActual: null, averageForecast: null, insufficientHistory: true,
      },
      branches: [],
    },
    ingredients: [],
    shrinkage: { maePercentagePoints: null, evaluatedWeeks: 0, branches: [] },
  },
});

describe("Predictive Analytics insight source", () => {
  it("renders layout-matched loading content and ignores stale response generations",()=>{
    const markup=renderToStaticMarkup(React.createElement(PredictiveAnalyticsSkeleton));
    expect(markup).toContain("data-predictive-analytics-skeleton");
    expect(markup).toContain("predictive-kpi-grid");
    expect(markup).toContain("Forecasted Sales");
    expect(markup).toContain("Forecast Shrinkage Rate");
    expect(markup).toContain("Forecast Accuracy");
    expect(markup).toContain("COGS MAE");
    expect(markup).toContain("Ingredient Usage Forecast Evaluation");
    expect(markup).not.toContain("animate-spin");
    expect(shouldApplyPredictiveResponse(3,4)).toBe(false);
    expect(shouldApplyPredictiveResponse(4,4)).toBe(true);
  });
  it("labels validated Gemini narratives distinctly", () => {
    expect(predictiveInsightSourceLabel("GOOGLE_GEMINI")).toBe("Generated by Gemini from calculated findings");
  });

  it("labels deterministic fallback insights without implying Gemini generated them", () => {
    expect(predictiveInsightSourceLabel("SYSTEM_ANALYSIS")).toBe("Generated from calculated system findings");
  });

  it("uses the authoritative response scope for Managers and preserves Owner all-branch scope", () => {
    expect(predictiveScopeLabel("manager", "Gulod / Main Branch", "All Branches")).toBe("Gulod / Main Branch");
    expect(predictiveScopeLabel("manager", undefined, "All Branches")).toBe("Assigned Branch");
    expect(predictiveScopeLabel("owner", undefined, "All Branches")).toBe("All Branches");
  });

  it("discloses that projected COGS is not verified historical procurement cost", () => {
    expect(PROJECTED_COGS_DISCLOSURE).toContain("configured ingredient costs");
    expect(PROJECTED_COGS_DISCLOSURE).toContain("not verified historical purchase costs");
    expect(FORECAST_EVALUATION_DISCLOSURE).toContain("retrospectively reconstructed");
    expect(FORECAST_EVALUATION_DISCLOSURE).toContain("Backfilled or corrected imports");
    expect(FORECAST_EVALUATION_DISCLOSURE).toContain("do not establish operational reliability");
  });
});

describe("Predictive Analytics data sufficiency messaging", () => {
  it("identifies Owner all-branch coverage as the least-covered branch", () => {
    const context = forecastContext(1, "LOW", null, 0);
    context.scope.branchId = null;
    context.scope.branchName = "All Branches";
    expect(predictiveCoverageLabel(context)).toBe("Minimum branch coverage: 1/28 recorded sales days");
    expect(predictiveDataSufficiency(context).lowHistoryMessage)
      .toBe("Preliminary forecast — the least-covered branch has only 1 recorded sales day; every included branch requires 28 days before projections and reorder suggestions are actionable.");
  });

  it("names active branches excluded from an Owner forecast for absent eligible history", () => {
    const context = forecastContext(1, "LOW", null, 0);
    context.scope.branchId = null;
    context.scope.branchName = "All Branches";
    context.scope.branchCoverage = {
      included: [{ branchId: "gulod", branchName: "Gulod / Main Branch" }],
      excluded: [{ branchId: "empty", branchName: "No History Branch", reason: "NO_ELIGIBLE_SALES_HISTORY" }],
    };
    expect(predictiveDataSufficiency(context).branchCoverageMessage)
      .toBe("Excluded for absent eligible sales history: No History Branch.");
  });

  it("explains LOW confidence when only one sales observation exists", () => {
    const result = predictiveDataSufficiency(forecastContext(1, "LOW", null, 0));
    expect(result.lowHistoryMessage).toBe("Preliminary forecast — only 1 recorded sales day is available; 28 are required before projections and reorder suggestions are actionable.");
  });

  it("explains why MAE is unavailable", () => {
    expect(predictiveDataSufficiency(forecastContext(1, "LOW", null, 0)).maeMessage)
      .toBe("MAE unavailable — insufficient historical data for backtesting.");
  });

  it("explains zero evaluated days", () => {
    expect(predictiveDataSufficiency(forecastContext(1, "LOW", null, 0)).evaluatedDaysMessage)
      .toBe("No historical forecasts could be evaluated yet.");
  });

  it("hides the notice when adequate evaluated history exists", () => {
    const result = predictiveDataSufficiency(forecastContext(90, "HIGH", 125, 30));
    expect(result).toMatchObject({ showNotice: false, lowHistoryMessage: null, maeMessage: null, evaluatedDaysMessage: null });
  });

  it("retains the API-provided branch scope in the notice", () => {
    expect(predictiveDataSufficiency(forecastContext(1, "LOW", null, 0, "Gulod / Main Branch")).scope)
      .toBe("Gulod / Main Branch");
  });

  it("explains unavailable and unsupported shrinkage-rate forecasts", () => {
    const insufficient = forecastContext(90, "HIGH", 125, 30);
    insufficient.summary.shrinkageForecastStatus = "INSUFFICIENT_HISTORICAL_DATA";
    expect(predictiveDataSufficiency(insufficient).shrinkageMessage)
      .toContain("at least 8 eligible complete weekly observations");
    const unsupported = forecastContext(90, "HIGH", 125, 30);
    unsupported.summary.shrinkageForecastStatus = "UNSUPPORTED_HORIZON";
    expect(predictiveDataSufficiency(unsupported).shrinkageMessage)
      .toContain("7 to 28 days");
  });
});

describe("Ingredient Usage Forecast Evaluation display", () => {
  it("reports Gulod's eligible ingredient and evaluated-day totals", () => {
    const eligible = Array.from({ length: 23 }, (_, index) => ingredientAccuracy({
      inventoryItemId: `eligible-${index}`,
      evaluatedDays: index < 21 ? 2 : 1,
      mae: 10,
    }));
    expect(ingredientEvaluationSummary([
      ...eligible,
      ingredientAccuracy({ inventoryItemId: "insufficient" }),
    ])).toEqual({ eligibleIngredients: 23, evaluatedDays: 44 });
  });

  it("distinguishes a valid limited MAE from unavailable history", () => {
    expect(ingredientEvaluationStatus(ingredientAccuracy({ evaluatedDays: 2, mae: 10 })))
      .toBe("limited evaluation");
    expect(ingredientEvaluationStatus(ingredientAccuracy()))
      .toBe("insufficient history");
    expect(ingredientEvaluationStatus(ingredientAccuracy({ incompatibleUnits: true })))
      .toBe("incompatible units");
  });
});
