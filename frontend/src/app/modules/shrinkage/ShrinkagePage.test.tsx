import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { AnomalyCaseViewButton, EvidenceDecisionButton, IncidentMatchStatus, MissingInvestigationVarianceButton, missingInvestigationVariancePath, SHRINKAGE_STATUS_FILTER_OPTIONS, ShrinkageAiAnalysisPanel } from "./ShrinkagePage";

describe("System-Detected Anomaly filters", () => {
  it("consolidates every existing status into one dropdown option set", () => {
    expect(SHRINKAGE_STATUS_FILTER_OPTIONS).toEqual([
      { value: "", label: "All Statuses" },
      { value: "DETECTED", label: "Needs Investigation" },
      { value: "VERIFIED", label: "Verified" },
      { value: "PENDING_REVIEW", label: "Pending Review" },
      { value: "REVIEWED", label: "Reviewed" },
    ]);
  });

  it("links a missing material case back to its exact variance date and ingredient", () => {
    expect(missingInvestigationVariancePath({ branchId: "branch-lipa", countItemId: "count-item-15", countDate: "2026-10-25", inventoryItemName: "Bacon & Eggs" })).toBe(
      "/inventory/variance?countDate=2026-10-25&branchId=branch-lipa&countItemId=count-item-15&query=Bacon%20%26%20Eggs",
    );
  });

  it("renders the variance locator as a visible outlined search action", () => {
    const markup = renderToStaticMarkup(React.createElement(MissingInvestigationVarianceButton, { onClick: () => undefined }));
    expect(markup).toContain("lucide-search");
    expect(markup).toContain("Find in Variance Records");
    expect(markup).toContain("border-[var(--app-primary)]");
    expect(markup).toContain("focus-visible:ring-[var(--app-primary)]");
    expect(markup).toContain("cursor-pointer");
  });

  it("renders the existing anomaly action as a bordered Eye and View button", () => {
    const markup = renderToStaticMarkup(React.createElement(AnomalyCaseViewButton, {
      reportNo: "SR-2026-00067",
      title: "View case",
      onClick: () => undefined,
    }));
    expect(markup).toContain("lucide-eye");
    expect(markup).toContain("View");
    expect(markup).toContain("View case SR-2026-00067");
    expect(markup).toContain("border-[var(--app-border)]");
  });
});

describe("AI-Assisted Shrinkage Analysis presentation", () => {
  it("shows content-shaped skeletons while analysis is generated", () => {
    const markup = renderToStaticMarkup(React.createElement(ShrinkageAiAnalysisPanel, {
      loading: true,
      result: null,
    }));
    expect(markup).toContain("data-shrinkage-ai-skeleton");
    expect(markup).toContain('aria-label="Generating advisory analysis"');
    expect(markup).toContain("motion-reduce:animate-none");
    expect(markup).not.toContain("currently unavailable");
  });

  it("labels a validated Gemini response and renders each advisory section", () => {
    const markup = renderToStaticMarkup(React.createElement(ShrinkageAiAnalysisPanel, {
      loading: false,
      result: {
        source: "GOOGLE_GEMINI",
        analysis: {
          observation: "A shortage was recorded.",
          risk: "The cause is not established.",
          recommendation: "Review the count and supporting records.",
          limitations: "Evidence is limited.",
        },
      },
    }));
    expect(markup).toContain("AI-Assisted Shrinkage Analysis");
    expect(markup).toContain("Generated by Gemini from calculated shrinkage findings");
    expect(markup).toContain("Observation");
    expect(markup).toContain("Risk / Pattern");
    expect(markup).toContain("Recommendation");
    expect(markup).toContain("Confidence / Limitation");
  });

  it("shows a non-AI unavailable state without claiming Gemini generated it", () => {
    const markup = renderToStaticMarkup(React.createElement(ShrinkageAiAnalysisPanel, {
      loading: false,
      result: { source: "UNAVAILABLE", analysis: null },
    }));
    expect(markup).toContain("AI-assisted analysis is currently unavailable.");
    expect(markup).not.toContain("Generated by Gemini");
  });
});

describe("incident evidence actions and match presentation",()=>{
  it("renders bordered, distinguishable evidence decision actions",()=>{
    const accept=renderToStaticMarkup(React.createElement(EvidenceDecisionButton,{action:"ACCEPTED",disabled:false,onClick:()=>undefined}));
    const reject=renderToStaticMarkup(React.createElement(EvidenceDecisionButton,{action:"REJECTED",disabled:false,onClick:()=>undefined}));
    expect(accept).toContain("Accept &amp; Link");
    expect(accept).toContain("border-[var(--app-primary)]");
    expect(reject).toContain(">Reject</button>");
    expect(reject).toContain("border-[var(--app-danger)]");
  });

  it("colors match labels from classification without changing UNVERIFIED status",()=>{
    const approximate=renderToStaticMarkup(React.createElement(IncidentMatchStatus,{matchQuality:"APPROXIMATE"}));
    const insufficient=renderToStaticMarkup(React.createElement(IncidentMatchStatus,{matchQuality:"INSUFFICIENT"}));
    expect(approximate).toContain("Approximate match · UNVERIFIED");
    expect(approximate).toContain("text-[var(--app-success)]");
    expect(insufficient).toContain("Insufficient match · UNVERIFIED");
    expect(insufficient).toContain("text-[var(--app-danger)]");
  });
});
